// Extracts the inner markup of every v1 widget figure from legacy/index.html
// into js/core/templates.js, so the same widgets can be mounted on new sheets.
import fs from "node:fs";
import { JSDOM } from "jsdom";

const dom = new JSDOM(fs.readFileSync(new URL("../legacy/index.html", import.meta.url), "utf8"));
const out = {};
for (const fig of dom.window.document.querySelectorAll("figure[data-widget]")) {
  const w = fig.dataset.widget;
  if (w === "opener" || out[w]) continue;
  out[w] = fig.innerHTML.replace(/\n\s+/g, "\n").trim()
    // the new design marks the true next token in red, not violet
    .replace(/violet = what actually comes next/g, "red = what actually comes next");
}
const js = `/* Generated by tools/make_templates.mjs from legacy/index.html. Do not edit. */\nwindow.WIDGET_TEMPLATES = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(new URL("../js/core/templates.js", import.meta.url), js);
console.log(Object.keys(out).length, "templates:", Object.keys(out).join(" "));
